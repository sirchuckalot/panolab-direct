"""Generate deterministic CBOR test vectors using only the Python standard library."""

from hashlib import sha256


def head(major, argument):
    if 0 <= argument < 24:
        return bytes([(major << 5) | argument])
    for additional, width in enumerate((1, 2, 4, 8), start=24):
        if 0 <= argument < 1 << (8 * width):
            return bytes([(major << 5) | additional]) + argument.to_bytes(width, "big")
    raise ValueError("CBOR argument outside uint64 range")


def encode(value):
    if type(value) is int:
        return head(0, value)
    if isinstance(value, str):
        data = value.encode("utf-8")
        return head(3, len(data)) + data
    if isinstance(value, bytes):
        return head(2, len(value)) + value
    if isinstance(value, list):
        return head(4, len(value)) + b"".join(map(encode, value))
    if isinstance(value, dict):
        return encode_pairs(sorted((encode(key), encode(item)) for key, item in value.items()))
    raise TypeError(type(value))


def encode_pairs(pairs):
    return head(5, len(pairs)) + b"".join(key + value for key, value in pairs)


def emit(name, data):
    print(f"static const uint8_t {name}[] = {{")
    for offset in range(0, len(data), 12):
        print("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 12]) + ",")
    print("};")


def main():
    image_digest = sha256(b"synthetic application image").digest()
    target = {
        "board_revision": "b",
        "board_id": "pano-g2",
        "bsp_profile": "pano-g2-revb/1",
        "fpga_part": "xc6slx150-2-fgg484",
    }
    provenance = {
        "dependency_pins": ["example@1"],
        "git_commit": "0123456789abcdef" * 2 + "01234567",
        "toolchain": "example-toolchain",
        "build_id": "fixture",
    }
    manifest = {
        "manifest_version": 1,
        "image_version": "1.2.3",
        "required_rescue_api": [1, 7],
        "image_length": 0x100000001,
        "image_sha256": image_digest,
        "image_role": "application",
        "config_format": "xilinx-spartan6-spi",
        "required_features": ["icap-return-v1"],
        "supported_targets": [target],
        "image_id": "fixture-app",
        "build_provenance": provenance,
    }
    valid = encode(manifest)
    minimal = encode(dict(
        manifest, image_length=1, required_rescue_api=[1, 0], required_features=[],
        build_provenance={key: value for key, value in provenance.items() if key != "build_id"},
    ))
    pairs = sorted((encode(key), encode(value)) for key, value in manifest.items())
    reordered = pairs.copy()
    reordered[0], reordered[1] = reordered[1], reordered[0]
    duplicate = [pairs[0], pairs[0], *pairs[2:]]

    def overlong_version(width):
        key = encode("manifest_version")
        additional = {1: 24, 2: 25, 4: 26, 8: 27}[width]
        return encode_pairs([
            (k, bytes([additional]) + (1).to_bytes(width, "big") if k == key else v)
            for k, v in pairs
        ])

    print("/* Generated by fixtures.py. */")
    emit("valid_manifest", valid)
    emit("valid_manifest_digest", sha256(valid).digest())
    emit("minimal_manifest", minimal)
    emit("minimal_manifest_digest", sha256(minimal).digest())
    emit("fixture_image_digest", image_digest)
    emit("reordered_keys", encode_pairs(reordered))
    emit("duplicate_keys", encode_pairs(duplicate))
    for width in (1, 2, 4, 8):
        emit(f"nonpreferred_uint_{width}", overlong_version(width))
    emit("wrong_board", encode(dict(manifest, supported_targets=[dict(target, board_id="pano-g1")])))
    emit("unknown_feature", encode(dict(manifest, required_features=["unknown-feature"])))
    emit("signing_fields", encode(dict(manifest, signature=bytes(64), signing_key_id="test-key")))
    emit("trailing_bytes", valid + encode(0))
    emit("wrong_role", encode(dict(manifest, image_role="rescue")))


if __name__ == "__main__":
    main()
